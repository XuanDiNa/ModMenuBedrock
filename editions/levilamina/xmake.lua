local function lamina_sdk()
    if binary_sdk and #binary_sdk > 0 then
        add_includedirs(path.join(binary_sdk, "include"))
        add_linkdirs(path.join(binary_sdk, "lib"))
        add_links("LeviLamina")
        add_defines("LL_PLAT_C", "ENTT_PACKED_PAGE=128", "ENTT_SPARSE_PAGE=4096", "ENTT_NO_MIXIN")
        add_packages(table.unpack(sdk_packages))
    else
        add_requires("levilamina 26.60.7", {configs = {target_type = "client"}})
        add_packages("levilamina")
    end
end

